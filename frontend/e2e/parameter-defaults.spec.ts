import { test, expect } from '@playwright/test';

test('技术参数直接显示默认数值、点击感叹号说明、模板变化和人工覆盖', async ({ page, request }) => {
  await page.goto('/');
  await page.getByRole('button', { name: '新建规划项目' }).click();
  await page.getByLabel('项目名称', { exact: true }).fill('技术默认值验收');
  await page.getByRole('button', { name: '创建项目', exact: true }).click();
  await page.getByRole('button', { name: '添加场景', exact: true }).click();
  const drawer = page.locator('.ant-drawer-content');
  await drawer.getByLabel('同时在线人数', { exact: true }).fill('100');
  await drawer.getByText('技术参数与默认值', { exact: true }).click();
  await expect(drawer.getByRole('spinbutton', { name: '每人每分钟请求', exact: true })).toHaveValue('0.5');
  const input = drawer.getByRole('spinbutton', { name: '输入 Token', exact: true });
  await expect(input).toHaveValue('2048');
  await expect(drawer.getByRole('spinbutton', { name: '可见输出 Token', exact: true })).toHaveValue('512');
  await expect(drawer.getByRole('spinbutton', { name: '额外推理 Token', exact: true })).toHaveValue('0');
  await expect(drawer.getByRole('spinbutton', { name: '每业务请求模型调用次数', exact: true })).toHaveValue('1');
  await expect(drawer.getByRole('spinbutton', { name: '输入阶段效率', exact: true })).toHaveValue('0.35');
  await expect(drawer.getByRole('spinbutton', { name: '直接覆盖请求/秒', exact: true })).toBeEmpty();
  await drawer.getByRole('button', { name: '输入 Token说明', exact: true }).click();
  const explanation = page.locator('.ant-popover:visible');
  await expect(explanation).toContainText('默认值：2048 Token/请求');
  await expect(explanation).toContainText('参数含义');
  await expect(explanation).toContainText('何时调整');
  await expect(explanation).toContainText('知识问答场景模板');
  await drawer.getByRole('button', { name: '输入 Token说明', exact: true }).click();
  await input.fill('4096');
  const template = drawer.getByRole('combobox', { name: '场景模板' });
  await template.focus();
  await template.press('ArrowDown');
  await page.locator('.ant-select-dropdown:visible').getByText('长报告/推理', { exact: true }).click();
  await expect(input).toHaveValue('4096');
  await expect(drawer.getByRole('spinbutton', { name: '每人每分钟请求', exact: true })).toHaveValue('0.05');
  await expect(drawer.getByRole('spinbutton', { name: '额外推理 Token', exact: true })).toHaveValue('4096');
  await input.fill('');
  await input.blur();
  await expect(input).toHaveValue('8192');
  const eta = drawer.getByRole('spinbutton', { name: '输入阶段效率', exact: true });
  await eta.fill('0.4'); await eta.blur();
  await eta.fill(''); await eta.blur();
  await expect(eta).toHaveValue('0.35');
  await drawer.getByRole('button', { name: '输入 Token说明', exact: true }).click();
  await expect(page.locator('.ant-popover:visible')).toContainText('默认值：8192 Token/请求');
  await page.screenshot({ path: '../docs/screenshots/05-parameter-defaults.png', fullPage: true });
  await drawer.getByRole('button', { name: '输入 Token说明', exact: true }).click();
  await drawer.locator('.ant-drawer-close').click();
  const saving = page.waitForResponse(r => r.request().method() === 'PATCH' && r.url().includes('/plans/'));
  await page.getByRole('button', { name: /保存方案/ }).click();
  const saved = await (await saving).json();
  const task = saved.payload.scenarios[0].components[0];
  expect(task.input_tokens).toBeNull();
  expect(Number(task.eta_prefill)).toBe(0.35);
  const preview = await request.post('/api/v1/preview-calculation', { data: { payload: saved.payload } });
  const result = await preview.json();
  expect(Number(result.pools[0].items[0].trace.variables.input_tokens_total)).toBe(8192);
});
